"""Generate ``gamedata/tac_attributes.py``: the client's TAC attribute registry.

The client's Template Attribute Collection stores each attribute under a 32-bit hash of its name,
and the hash alone does not say how the value is encoded. The registry says that: each attribute is
declared as ``new StringAttrs("Name")``, ``new IntAttrs("Name", ...)``, ``new TACAttrs("Name", ...)``
or ``new ListAttrs("Name")`` in ``Game/Shared/Mechanics/<Kind>Attrs.cs``. The string argument is what is
hashed; a field name may differ from it (``AdditionalCardText`` is registered as "AdditionCardText").

Run from the repo root:

    python3 AssetExtraction/extract_tac_attributes.py
"""

import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
MECHANICS = os.path.join(ROOT, "hex-private", "HexClient", "Assembly-CSharp-firstpass",
                         "Game", "Shared", "Mechanics")
OUTPUT = os.path.join(ROOT, "gamedata", "tac_attributes.py")
KINDS = ("String", "Int", "TAC", "List")
DECLARATION = re.compile(r'public static (\w+)Attrs \w+ = new \1Attrs\("(\w+)"')


def registry():
    """Attribute name -> kind ("String", "Int", "TAC" or "List"). Raises on a clash."""
    found = {}
    for kind in KINDS:
        with open(os.path.join(MECHANICS, f"{kind}Attrs.cs"), encoding="utf-8-sig") as stream:
            text = stream.read()
        for match in DECLARATION.finditer(text):
            if match.group(1) != kind:
                continue
            name = match.group(2)
            if name in found:
                raise ValueError(f"TAC attribute {name} is declared twice")
            found[name] = kind
    return found


def render(attributes):
    lines = [
        '"""The client\'s TAC attribute registry (generated by AssetExtraction/extract_tac_attributes.py;',
        'do not edit by hand). ``ATTRIBUTES`` maps each attribute name to how its value is encoded:',
        '"String", "Int", "TAC" (a nested collection) or "List" (a collection of nested entries)."""',
        "",
        "ATTRIBUTES: dict[str, str] = {",
    ]
    for name in sorted(attributes):
        lines.append(f"    {name!r}: {attributes[name]!r},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    attributes = registry()
    with open(OUTPUT, "w", encoding="utf-8") as stream:
        stream.write(render(attributes))
    print(f"wrote {OUTPUT}: {len(attributes)} attributes")


if __name__ == "__main__":
    main()
